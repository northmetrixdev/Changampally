/**
 * @file lib/rag/generator.ts
 * Generates responses using Google Gemini API and retrieved website context.
 * Strictly adheres to verified website context and returns fallback when unanswerable.
 */

import { ChatMessage, RetrievalResult } from "./types";

const GEMINI_API_URL = "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent";

export async function generateRAGResponse(
  userQuery: string,
  retrievedChunks: RetrievalResult[],
  conversationHistory: ChatMessage[] = []
): Promise<string> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error("GEMINI_API_KEY is not configured.");
  }

  // Construct context string from retrieved chunks
  const contextText = retrievedChunks.length > 0
    ? retrievedChunks
        .map((r, i) => `[Source ${i + 1}: ${r.chunk.title}]\n${r.chunk.content}`)
        .join("\n\n")
    : "No directly matching content found in knowledge base.";

  const systemInstruction = `You are the official, compassionate AI Assistant for Changampally Integrated Healthcare (founded 1300 AD in Kerala, India).
Your sole purpose is to answer visitor questions regarding Changampally's centres, doctors, treatments, Ayurvedic heritage, and contact details.

Rules:
1. Answer strictly using ONLY the provided Changampally Website Context below.
2. If the context does not contain the necessary information to answer the question, clearly and politely respond:
   "I do not have specific information regarding that on the Changampally website. Please contact our reception desk at +91 9072666104 or email remediumchangampally@gmail.com for direct assistance."
3. Do not invent medical diagnoses, prescription doses, doctor names, pricing, or facilities not stated in the context.
4. Maintain a warm, respectful, and professional tone suitable for a healthcare institution.
5. Format your answers clearly using concise paragraphs or bullet points where appropriate.

Changampally Website Context:
${contextText}`;

  // Format message history for Gemini API
  const contents = [
    {
      role: "user",
      parts: [{ text: systemInstruction }],
    },
    {
      role: "model",
      parts: [{ text: "Understood. I will answer visitors accurately and warmly based strictly on Changampally's verified website context." }],
    },
  ];

  // Append recent conversation history (up to last 4 messages)
  const recentHistory = conversationHistory.slice(-4);
  for (const msg of recentHistory) {
    contents.push({
      role: msg.role === "assistant" ? "model" : "user",
      parts: [{ text: msg.content }],
    });
  }

  // Append current user message
  contents.push({
    role: "user",
    parts: [{ text: userQuery }],
  });

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 12000);

  try {
    const response = await fetch(`${GEMINI_API_URL}?key=${apiKey}`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        contents,
        generationConfig: {
          temperature: 0.2,
          maxOutputTokens: 600,
        },
      }),
      signal: controller.signal,
    });

    clearTimeout(timeoutId);

    if (!response.ok) {
      const errorData = await response.json().catch(() => ({}));
      console.error("Gemini API Error:", response.status, errorData);
      throw new Error(`Gemini API returned status ${response.status}`);
    }

    const data = await response.json();
    const candidateText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidateText) {
      throw new Error("No response generated by Gemini model.");
    }

    return candidateText.trim();
  } catch (err: unknown) {
    clearTimeout(timeoutId);
    if (err instanceof Error && err.name === "AbortError") {
      throw new Error("Request to Gemini API timed out.");
    }
    throw err;
  }
}

